<x-marketing.legal-layout title="Shipping Policy"
    metaDescription="CreatorFlow shipping policy — how brands should ship product to creators in barter and seeding campaigns.">

    <p>CreatorFlow itself does not ship physical goods — we are a software platform. This policy explains our expectations of <strong>brands</strong> when they ship product to creators.</p>

    <h2>Timelines</h2>
    <ul>
        <li>Brands must dispatch product within <strong>3 business days</strong> of an accepted invitation for barter or seeding campaigns.</li>
        <li>Tracking numbers must be entered into the campaign assignment page so creators receive automatic updates.</li>
    </ul>

    <h2>Costs and duties</h2>
    <p>Shipping, insurance, and any duties/GST are the brand's responsibility. Creators are not required to pay to receive product.</p>

    <h2>Damaged or lost shipments</h2>
    <p>If a shipment is lost or arrives damaged, brands must ship a replacement within 5 business days or the assignment is voided without penalty to the creator.</p>

    <h2>International</h2>
    <p>Where a brand chooses to work with creators outside India, all customs paperwork is the brand's responsibility.</p>
</x-marketing.legal-layout>
