    metaDescription="CreatorPlex content guidelines — what creators can and cannot post in brand campaigns.">

    <p>These guidelines apply to every piece of content created through a CreatorPlex campaign.</p>

    <h2>Disclosure</h2>
    <ul>
        <li>Every paid or barter post must include <strong>#ad</strong> or the platform's native "Paid partnership" tag as required by the ASCI code, Instagram guidelines, and FTC where applicable.</li>
        <li>Discount codes should be presented clearly and visibly.</li>
    </ul>

    <h2>Truthfulness</h2>
    <ul>
        <li>Do not make claims (medical, financial, legal, cosmetic) that cannot be substantiated by the brand.</li>
        <li>Do not compare directly against a named competitor unless the brand's brief permits it.</li>
    </ul>

    <h2>Safety and inclusion</h2>
    <ul>
        <li>No hate speech, discrimination, sexually explicit content, glorification of violence, or content involving minors without parental consent.</li>
        <li>No dangerous stunts.</li>
    </ul>

    <h2>Ownership</h2>
    <ul>
        <li>Do not use copyrighted music, footage, or images you don't have rights to.</li>
        <li>Only include people in your content who have given their consent.</li>
    </ul>

    <h2>Enforcement</h2>
    <p>Violations may lead to content rejection, campaign removal, escrow release to the brand, and — for repeat offences — account suspension.</p>
</x-marketing.legal-layout>
