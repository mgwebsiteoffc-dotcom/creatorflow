        <li><strong>Brand data</strong> — company name, GSTIN, billing address, payment method, campaigns, briefs, products, invoices.</li>
        <li><strong>Creator data</strong> — display name, city, country, niches, follower counts, engagement rate, connected social handles, bank/UPI payout details, KYC documents.</li>
