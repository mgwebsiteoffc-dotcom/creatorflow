    </ul>

    <h2>2. Why we process it</h2>
    <ul>
        <li>To run the Service: match brands + creators, deliver campaigns, process payouts, invoice.</li>
        <li>To comply with tax + KYC obligations under Indian law.</li>
        <li>To detect fraud and abuse.</li>
        <li>To send transactional and (with consent) marketing emails.</li>
    </ul>

    <h2>3. Who we share data with</h2>
    <ul>
        <li>Payment processors (Stripe, Razorpay) — only what's needed to charge or pay out.</li>
        <li>Shopify + connected commerce platforms — order-related data when you authorise the connection.</li>
        <li>Analytics and error-reporting tools (aggregated / de-identified where possible).</li>
        <li>Government authorities when required by law.</li>
    </ul>

    <p>We do <strong>not</strong> sell your personal data. We do not share creator PII with brands beyond what the creator has chosen to publish on their profile.</p>

